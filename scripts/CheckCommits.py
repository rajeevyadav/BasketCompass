"""Fail closed on unauthorized commit metadata; never mutate commit history.

The check rejects assistant/bot *attribution* — co-author trailers, "generated by
<tool>" credits, the robot emoji, or a non-owner author/committer identity. It does
NOT reject the bare letters of a tool's name in ordinary prose: a commit that merely
describes the no-assistant-attribution policy is legitimate. (An earlier version
matched the two-letter acronym anywhere and wrongly flagged the seed commit, which
states that very policy.)
"""
import os
import re
import subprocess
import sys

owner = os.environ.get('OWNER_EMAIL', '').strip()
if not owner:
    sys.exit('Set OWNER_EMAIL to the owner-authorized commit email.')

# Attribution patterns (case-insensitive, multiline). Each targets a credit line
# or trailer, not prose: a co-author trailer, a "generated/authored by <tool>"
# credit, or the robot emoji. A non-owner identity is checked separately below.
ATTRIBUTION = re.compile(
    r'^\s*co-authored-by:\s'
    r'|generated\s+(?:with|by)\b[^\n]*\b(?:ai|claude|copilot|chatgpt|gemini|codex|anthropic|openai|bard)\b'
    r'|\b(?:authored|written|created)\s+by\b[^\n]*\b(?:claude|copilot|chatgpt|gemini|codex|anthropic)\b'
    r'|\U0001F916',
    re.IGNORECASE | re.MULTILINE,
)

raw = subprocess.check_output(
    ['git', 'log', '--all', '--format=%H%x00%ae%x00%ce%x00%B%x00']).decode()
parts = raw.split('\0')
for i in range(0, len(parts) - 3, 4):
    sha, author, committer, message = parts[i:i + 4]
    if author != owner or committer != owner:
        sys.exit('Unauthorized commit identity: ' + sha.strip())
    if ATTRIBUTION.search(message):
        sys.exit('Prohibited commit attribution: ' + sha.strip())
print('Commit metadata policy passed.')
